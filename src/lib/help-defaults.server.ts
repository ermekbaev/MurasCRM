/**
 * Заводит стартовые статьи, если база знаний пуста. Идемпотентно: если статьи
 * уже есть (свои или прежние), ничего не трогает.
 */
export async function ensureDefaultHelpArticles(): Promise<void> {
  const count = await prisma.helpArticle.count();
  if (count > 0) return;
  await prisma.helpArticle.createMany({
    data: DEFAULT_HELP_ARTICLES.map((a, i) => ({ ...a, sortOrder: i })),
    skipDuplicates: true,
  });
}
